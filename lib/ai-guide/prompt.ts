function generated() {
  const audience = { all: "全員", manager: "店長・管理者", admin: "管理者（本部）" } as const;
  const menus = NAV.flatMap((s) => s.items.map((i) => `- ${s.title}：${i.label}（${i.href}）…使える人：${audience[i.audience]}`)).join("\n");
  const reports = REPORT_TYPES.map((t) => `- 【${CATEGORIES[t.category].label}】${t.title}：${t.description}`).join("\n");
  return `## メニューの一覧（自動）\n${menus}\n\n## 報告窓口の種類（自動）\n${reports}`;
}

